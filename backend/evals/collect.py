"""Collect real solicitation text for the eval set with Tavily extract.

  python -m evals.collect URL [URL ...]

Writes evals/rfps/<slug>.json with empty labels for a human to fill in. Labels are
hand-assigned, never generated by the model under test.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app import db, tavily_client  # noqa: E402

OUT = Path(__file__).resolve().parent / "rfps"


def slug(url: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", url.lower().split("//", 1)[-1])[:60].strip("-")


def main(urls: list[str]) -> None:
    db.init()
    OUT.mkdir(exist_ok=True)
    for page in tavily_client.extract(urls):
        text = page.get("raw_content") or ""
        if len(text) < 500:
            print(f"skip (too short): {page.get('url')}")
            continue
        path = OUT / f"{slug(page['url'])}.json"
        if path.exists():
            continue
        path.write_text(json.dumps({
            "id": path.stem,
            "url": page["url"],
            "text": text[:60000],
            "labels": {"set_aside": None, "naics": None, "due_date": None, "eligible": None, "fit": None},
        }, indent=1))
        print(f"saved {path.name} ({len(text)} chars)")


if __name__ == "__main__":
    main(sys.argv[1:])
